"""Builds the GitHub Pages site and the addresses the node service reads.

    python docs/build_page.py [node-api-url]

Writes docs/index.html (the page, with the deployed addresses and the proof's results built in), docs/channel.js and
docs/rpc.js (lib/channel.mjs and lib/rpc.mjs with their one import pointed at a browser build of ethers), and
lib/addresses.mjs (what api/node.mjs needs, so the Vercel function reads no JSON file).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
read = lambda *p: open(os.path.join(*p), encoding="utf-8").read()
write = lambda path, text: open(path, "w", encoding="utf-8", newline="\n").write(text)
dep = json.loads(read(ROOT, "deployment.json"))
node_api = sys.argv[1] if len(sys.argv) > 1 else "https://countersign-node.vercel.app/api/node"

# The node service's addresses first: they need nothing but deployment.json.
write(os.path.join(ROOT, "lib", "addresses.mjs"), "// Generated by docs/build_page.py from deployment.json.\nexport default " + json.dumps(
    {"channel_hub": dep["channel_hub"]["address"], "countersign": dep["countersign"]["address"], "court": dep["court"]["address"],
     "token": dep["token"]["address"], "node": dep["roles"]["node"], "validator_id": dep["validator_id"]}, indent=2) + ";\n")
exists = lambda *p: os.path.exists(os.path.join(ROOT, *p))
# The proof as far as it has run: proof.json and flow_proof.json once complete, the resumable state files before that.
proof = json.loads(read(ROOT, "results", "proof.json" if exists("results", "proof.json") else "state.json"))
# flow_proof.json, never flow_state.json: the state file also holds the proof wallet's throwaway key and is not published.
flow = json.loads(read(ROOT, "results", "flow_proof.json"))
keep = {"hub": dep["channel_hub"]["address"], "countersign": dep["countersign"]["address"], "court": dep["court"]["address"],
        "token": dep["token"]["address"], "node": dep["roles"]["node"], "validator_id": dep["validator_id"]}
attack = {"reviewer": flow["reviewer"], "E": {"cid": flow["channels"]["E"]}, "F": {"cid": flow["channels"]["F"]},
          "F_10": {"caseId": flow["cases"]["F_10"]["caseId"], "state": flow["cases"]["F_10"]["state"]},
          "F_2": {"caseId": flow["cases"]["F_2"]["caseId"], "state": flow["cases"]["F_2"]["state"]}}
checks = [{"label": c["label"], "ok": c["ok"], "detail": c.get("detail", "")} for c in proof["checks"] + flow["checks"]]
errors = []
for name in ("Countersign", "ChannelHub"):
    for x in json.loads(read(ROOT, "evm", "abi", name + ".json")):
        if x.get("type") == "error" and all(e.get("name") != x["name"] for e in errors):
            errors.append(x)

script = (read(HERE, "page_script.html").replace("__DEP__", json.dumps(keep)).replace("__PROOF__", json.dumps({"checks": checks, "attack": attack}))
          .replace("__ERRORS__", json.dumps(errors)).replace("__NODE_API__", json.dumps(node_api)))
head = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Countersign: when the other side won't sign</title>
<meta name="description" content="An open source GenLayer testnet demo: Internet Court as a Yellow Nitrolite signature validator. When a node refuses to sign the settlement the terms require, the court's countersignature stands in for it on Yellow's own ChannelHub." />
<link rel="icon" href="logo.svg" />
<link rel="preconnect" href="https://fonts.googleapis.com" />
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
<link href="https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,400..600;1,9..144,400..600&family=Inter+Tight:wght@400;500;600&family=JetBrains+Mono:wght@400;500;700&display=swap" rel="stylesheet" />
<style>
""" + read(HERE, "design.css") + """
</style>
</head>
"""
write(os.path.join(HERE, "index.html"), head + read(HERE, "page_body.html") + script)
for name in ("channel", "rpc"):
    src = read(ROOT, "lib", name + ".mjs").replace("from 'ethers';", "from 'https://esm.sh/ethers@6.13.4';")
    write(os.path.join(HERE, name + ".js"), src)
print("docs/index.html, channel.js, rpc.js and lib/addresses.mjs written; node API", node_api)
